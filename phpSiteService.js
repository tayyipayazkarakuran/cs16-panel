function normalizeDomain(value) {
    const domain = String(value || '').trim().toLowerCase().replace(/^https?:\/\//, '').replace(/\/.*$/, '');
    if (!domain) return null;
    if (domain.length > 190 || !/^(?=.{1,190}$)([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/.test(domain)) {
        throw httpError(400, 'Geçerli bir alan adı girin (örn. www.sunucum.com).');
    }
    const panelHost = new URL(cfg.panelPublicUrl).hostname.toLowerCase();
    if (domain === panelHost) throw httpError(400, 'Panel alan adı bir siteye atanamaz.');
    return domain;
}

async function writeDomainMap() {
    ensureRoots();
    const [rows] = await panelDb.assertPool().query(
        'SELECT port, php_domain FROM panel_servers WHERE php_domain IS NOT NULL AND is_pool = 0 AND suspended = 0'
    );
    const lines = ['# Generated by the CS 1.6 panel: <domain> <port>'];
    rows.forEach(r => { lines.push(`${r.php_domain} ${r.port}`); });
    const target = path.join(WWW, PANEL_DIR, 'domains.map');
    const tmp = `${target}.tmp`;
    fs.writeFileSync(tmp, `${lines.join('\n')}\n`);
    fs.renameSync(tmp, target);
}

async function setDomain(record, domainInput) {
    const domain = normalizeDomain(domainInput);
    try {
        await panelDb.updateServerContainer(record.container_id, {
            php_domain: domain,
            php_url: cfg.phpSiteUrl(record.port, domain)
        });
    } catch (e) {
        if (e.code === 'ER_DUP_ENTRY') throw httpError(409, 'Bu alan adı başka bir sitede kullanılıyor.');
        throw e;
    }
    await writeDomainMap();
    const updated = await panelDb.getServerByContainerId(record.container_id);
    writeSiteConfig(updated);
    return updated;
}

function siteInfo(record) {
    const port = portOf(record);
    return {
        port,
        url: cfg.phpSiteUrl(port),
        domain: record.php_domain || null,
        domainUrl: record.php_domain ? cfg.phpSiteUrl(port, record.php_domain) : null,
        root: `${SITES_DIR}/${port}`,
        usage: siteUsage(record),
        database: {
            host: cfg.mysql.internalHost,
            port: cfg.mysql.internalPort,
            name: record.db_name,
            user: record.db_username
        },
        phpVersion: '8.2',
        templates: TEMPLATES
    };
}

